"""
Standalone UV Detector Data Plotter

This script opens a plotting window to visualize UV-Vis data from CSV files
generated by the Ocean Optics UV detector during continuous monitoring.

The CSV format is:
    Time(s), wavelength1, wavelength2, ...

The plot displays absorbance at each target wavelength over time.

Usage:
    python uv_plot_gui.py --csv-file <path_to_uv_csv>
    python uv_plot_gui.py --csv-file <path_to_uv_csv> --interval-ms 5000
    python uv_plot_gui.py  # Uses demo data if no file specified
"""

import tkinter as tk
from tkinter import ttk
import argparse
from pathlib import Path
import pandas as pd
import matplotlib
matplotlib.use("TkAgg")
import matplotlib.pyplot as plt
from matplotlib.backends.backend_tkagg import FigureCanvasTkAgg, NavigationToolbar2Tk


class UVDataPlotWindow(tk.Toplevel):
    """Window for plotting UV-Vis time-course data from CSV files."""
    
    def __init__(self, master, csv_path, spectrum_path=None, update_interval_ms=5000):
        """
        Args:
            master: Parent Tk window
            csv_path: Path to the UV time-course CSV file
            spectrum_path: Optional path to spectrum CSV file (if None, will auto-detect)
            update_interval_ms: Auto-update interval in milliseconds
        """
        super().__init__(master)
        self.title("UV-Vis Data Monitor")
        self.geometry("1200x650")
        
        self.csv_path = Path(csv_path)
        self.spectrum_path = Path(spectrum_path) if spectrum_path else None
        self.update_interval_ms = update_interval_ms
        self._auto_update_active = False
        self._auto_update_job = None
        
        # Time range filtering
        self.time_min = None  # None means no limit
        self.time_max = None
        
        self._build_ui()
        self._build_plot()
        
        # Initial plot
        self.update_plot()
        
        # Start auto-update after a short delay
        self.after(500, self.start_auto_update)
    
    def _build_ui(self):
        """Build the control panel UI."""
        # Top control frame
        control_frame = ttk.Frame(self, padding=10)
        control_frame.pack(side=tk.TOP, fill=tk.X)
        
        # File path label
        ttk.Label(control_frame, text="CSV File:").pack(side=tk.LEFT, padx=(0, 5))
        file_label = ttk.Label(control_frame, text=str(self.csv_path), 
                               foreground="blue", relief=tk.SUNKEN, padding=5)
        file_label.pack(side=tk.LEFT, fill=tk.X, expand=True, padx=(0, 10))
        
        # Auto-update controls
        self.auto_update_btn = ttk.Button(control_frame, text="Stop Auto-Update", 
                                          command=self.toggle_auto_update)
        self.auto_update_btn.pack(side=tk.LEFT, padx=5)
        
        ttk.Button(control_frame, text="Refresh Now", 
                  command=self.update_plot).pack(side=tk.LEFT, padx=5)
        
        # Status label
        self.status_label = ttk.Label(control_frame, text="", foreground="green")
        self.status_label.pack(side=tk.LEFT, padx=10)
        
        # Time range control frame
        range_frame = ttk.Frame(self, padding=(10, 0, 10, 5))
        range_frame.pack(side=tk.TOP, fill=tk.X)
        
        ttk.Label(range_frame, text="Time Range:").pack(side=tk.LEFT, padx=(0, 5))
        
        # Quick range buttons
        ttk.Button(range_frame, text="Last 10 min", 
                  command=lambda: self.set_time_range_minutes(10)).pack(side=tk.LEFT, padx=2)
        ttk.Button(range_frame, text="Last 30 min", 
                  command=lambda: self.set_time_range_minutes(30)).pack(side=tk.LEFT, padx=2)
        ttk.Button(range_frame, text="Full Range", 
                  command=self.reset_time_range).pack(side=tk.LEFT, padx=2)
        
        # Min/Max time entry fields
        ttk.Label(range_frame, text="  Min (s):").pack(side=tk.LEFT, padx=(10, 2))
        self.time_min_var = tk.StringVar()
        self.time_min_entry = ttk.Entry(range_frame, textvariable=self.time_min_var, width=8)
        self.time_min_entry.pack(side=tk.LEFT, padx=2)
        
        ttk.Label(range_frame, text="Max (s):").pack(side=tk.LEFT, padx=(5, 2))
        self.time_max_var = tk.StringVar()
        self.time_max_entry = ttk.Entry(range_frame, textvariable=self.time_max_var, width=8)
        self.time_max_entry.pack(side=tk.LEFT, padx=2)
        
        ttk.Button(range_frame, text="Apply", 
                  command=self.apply_custom_time_range).pack(side=tk.LEFT, padx=5)
    
    def _build_plot(self):
        """Build the matplotlib figure and canvas."""
        # Two subplots: spectrum (left) and time course (right)
        self.fig, (self.ax_spec, self.ax_time) = plt.subplots(1, 2, figsize=(14, 6))
        
        # Spectrum plot
        self.ax_spec.set_xlabel("Wavelength (nm)")
        self.ax_spec.set_ylabel("Absorbance")
        self.ax_spec.set_title("Full Spectrum")
        self.ax_spec.grid(True, alpha=0.3)
        
        # Time-course plot
        self.ax_time.set_xlabel("Time (s)")
        self.ax_time.set_ylabel("Absorbance")
        self.ax_time.set_title("Time Course")
        self.ax_time.grid(True, alpha=0.3)
        
        self.canvas = FigureCanvasTkAgg(self.fig, master=self)
        self.canvas.get_tk_widget().pack(fill=tk.BOTH, expand=True, padx=10, pady=(5, 10))
        
        # Add matplotlib navigation toolbar at top
        toolbar_frame = ttk.Frame(self)
        toolbar_frame.pack(side=tk.TOP, fill=tk.X, before=self.canvas.get_tk_widget())
        self.toolbar = NavigationToolbar2Tk(self.canvas, toolbar_frame)
        self.toolbar.update()
        
        self.fig.tight_layout()
    
    def update_plot(self):
        """Read the CSV and update both plots."""
        try:
            if not self.csv_path.exists():
                self.status_label.config(text=f"File not found: {self.csv_path.name}", 
                                        foreground="red")
                return
            
            # Read time-course CSV
            df = pd.read_csv(self.csv_path)
            
            if df.empty or "Time(s)" not in df.columns:
                self.status_label.config(text="Invalid CSV format", foreground="red")
                return
            
            # Update time-course plot (right)
            self._update_time_plot(df)
            
            # Update spectrum plot (left)
            self._update_spectrum_plot()
            
            self.fig.tight_layout()
            self.canvas.draw()
            
            # Update status
            time_col = df["Time(s)"]
            last_time = time_col.iloc[-1] if len(time_col) > 0 else 0
            self.status_label.config(
                text=f"Updated: {len(df)} points, last time: {last_time:.1f}s",
                foreground="green"
            )
            
        except Exception as e:
            self.status_label.config(text=f"Error: {str(e)}", foreground="red")
    
    def _update_time_plot(self, df):
        """Update the time-course plot (right side)."""
        self.ax_time.clear()
        
        # Apply time range filtering
        time_col = df["Time(s)"]
        mask = pd.Series([True] * len(df))
        
        if self.time_min is not None:
            mask &= (time_col >= self.time_min)
        if self.time_max is not None:
            mask &= (time_col <= self.time_max)
        
        df_filtered = df[mask]
        
        if df_filtered.empty:
            self.ax_time.text(0.5, 0.5, "No data in selected time range", 
                             ha='center', va='center', transform=self.ax_time.transAxes,
                             fontsize=10, color='orange')
            self.ax_time.set_xlabel("Time (s)", fontsize=11)
            self.ax_time.set_ylabel("Absorbance", fontsize=11)
            self.ax_time.set_title("Time Course at Target Wavelengths", fontsize=12)
            self.ax_time.grid(True, alpha=0.3)
            return
        
        # Plot each wavelength column (all columns except Time(s))
        time_col_filtered = df_filtered["Time(s)"]
        wavelength_cols = [col for col in df_filtered.columns if col != "Time(s)"]
        
        if not wavelength_cols:
            self.ax_time.text(0.5, 0.5, "No wavelength data", 
                             ha='center', va='center', transform=self.ax_time.transAxes)
            return
        
        for wl_col in wavelength_cols:
            try:
                # Try to convert column name to float for label (e.g., "409.0" -> 409.0 nm)
                wl_value = float(wl_col)
                label = f"{wl_value:.1f} nm"
            except ValueError:
                label = wl_col
            
            self.ax_time.plot(time_col_filtered, df_filtered[wl_col], marker='o', markersize=4, 
                             label=label, linewidth=1.5)
        
        self.ax_time.set_xlabel("Time (s)", fontsize=11)
        self.ax_time.set_ylabel("Absorbance", fontsize=11)
        self.ax_time.set_title("Time Course at Target Wavelengths", fontsize=12)
        self.ax_time.grid(True, alpha=0.3)
        self.ax_time.legend(loc='best', fontsize=9)
    
    def _update_spectrum_plot(self):
        """Update the full spectrum plot (left side)."""
        self.ax_spec.clear()
        
        # Use explicitly provided spectrum path, or auto-detect
        if self.spectrum_path and self.spectrum_path.exists():
            spectrum_csv = self.spectrum_path
        else:
            # Look for most recent spectrum snapshot CSV in same directory
            spectrum_csv = self._find_latest_spectrum_csv()
        
        if spectrum_csv is None or not spectrum_csv.exists():
            # No spectrum file found, show placeholder
            self.ax_spec.text(0.5, 0.5, "No spectrum data found\n(looking for absorbance_*.csv)", 
                             ha='center', va='center', transform=self.ax_spec.transAxes,
                             fontsize=10, color='gray')
            self.ax_spec.set_xlabel("Wavelength (nm)", fontsize=11)
            self.ax_spec.set_ylabel("Absorbance", fontsize=11)
            self.ax_spec.set_title("Full Spectrum (Latest)", fontsize=12)
            self.ax_spec.grid(True, alpha=0.3)
            return
        
        try:
            # Read spectrum CSV (format: Wavelength (nm),Absorbance)
            spec_df = pd.read_csv(spectrum_csv)
            
            # Handle different possible column names
            wl_col = None
            abs_col = None
            
            for col in spec_df.columns:
                col_lower = col.lower()
                if 'wavelength' in col_lower:
                    wl_col = col
                elif 'absorbance' in col_lower or 'intensity' in col_lower:
                    abs_col = col
            
            if wl_col is None or abs_col is None:
                # Try first two columns as fallback
                if len(spec_df.columns) >= 2:
                    wl_col = spec_df.columns[0]
                    abs_col = spec_df.columns[1]
                else:
                    raise ValueError("Cannot identify wavelength and absorbance columns")
            
            wavelengths = spec_df[wl_col]
            absorbance = spec_df[abs_col]
            
            self.ax_spec.plot(wavelengths, absorbance, linewidth=1.5, color='blue')
            self.ax_spec.set_xlabel("Wavelength (nm)", fontsize=11)
            self.ax_spec.set_ylabel("Absorbance", fontsize=11)
            self.ax_spec.set_title(f"Full Spectrum: {spectrum_csv.name}", fontsize=12)
            self.ax_spec.grid(True, alpha=0.3)
            
        except Exception as e:
            # Error reading spectrum file
            self.ax_spec.text(0.5, 0.5, f"Error reading spectrum:\n{str(e)}", 
                             ha='center', va='center', transform=self.ax_spec.transAxes,
                             fontsize=9, color='red')
            self.ax_spec.set_xlabel("Wavelength (nm)", fontsize=11)
            self.ax_spec.set_ylabel("Absorbance", fontsize=11)
            self.ax_spec.set_title("Full Spectrum (Error)", fontsize=12)
            self.ax_spec.grid(True, alpha=0.3)
    
    def _find_latest_spectrum_csv(self):
        """Find the most recent spectrum snapshot CSV in the same directory."""
        # Look for files matching pattern: absorbance_*.csv or *_spectrum.csv
        directory = self.csv_path.parent
        
        # Try multiple patterns
        patterns = ['absorbance_*.csv', '*_spectrum.csv', '*blank*.csv', '*dark*.csv']
        candidates = []
        
        for pattern in patterns:
            candidates.extend(directory.glob(pattern))
        
        if not candidates:
            return None
        
        # Return the most recently modified file
        latest = max(candidates, key=lambda p: p.stat().st_mtime)
        return latest
    
    def start_auto_update(self):
        """Start automatic periodic updates."""
        self.stop_auto_update()  # Cancel any existing job first
        self._auto_update_active = True
        self.auto_update_btn.config(text="Stop Auto-Update")
        self._schedule_next_update()
    
    def stop_auto_update(self):
        """Stop automatic updates."""
        self._auto_update_active = False
        if self._auto_update_job is not None:
            self.after_cancel(self._auto_update_job)
            self._auto_update_job = None
        self.auto_update_btn.config(text="Start Auto-Update")
    
    def toggle_auto_update(self):
        """Toggle auto-update on/off."""
        if self._auto_update_active:
            self.stop_auto_update()
        else:
            self.start_auto_update()
    
    def _schedule_next_update(self):
        """Schedule the next update tick."""
        if self._auto_update_active:
            self.update_plot()
            self._auto_update_job = self.after(self.update_interval_ms, self._schedule_next_update)
    
    def set_time_range_minutes(self, minutes):
        """Set time range to show last N minutes from the most recent data point."""
        try:
            if not self.csv_path.exists():
                return
            
            df = pd.read_csv(self.csv_path)
            if df.empty or "Time(s)" not in df.columns:
                return
            
            max_time = df["Time(s)"].max()
            self.time_min = max(0, max_time - minutes * 60)
            self.time_max = None  # No upper limit
            
            # Update entry fields
            self.time_min_var.set(f"{self.time_min:.1f}")
            self.time_max_var.set("")
            
            self.update_plot()
        except Exception as e:
            self.status_label.config(text=f"Error setting range: {str(e)}", foreground="red")
    
    def reset_time_range(self):
        """Reset to show full time range."""
        self.time_min = None
        self.time_max = None
        self.time_min_var.set("")
        self.time_max_var.set("")
        self.update_plot()
    
    def apply_custom_time_range(self):
        """Apply custom min/max time range from entry fields."""
        try:
            min_str = self.time_min_var.get().strip()
            max_str = self.time_max_var.get().strip()
            
            self.time_min = float(min_str) if min_str else None
            self.time_max = float(max_str) if max_str else None
            
            # Validate range
            if self.time_min is not None and self.time_max is not None:
                if self.time_min >= self.time_max:
                    self.status_label.config(text="Min must be less than Max", foreground="red")
                    return
            
            self.update_plot()
        except ValueError:
            self.status_label.config(text="Invalid time range values", foreground="red")


def open_uv_plot_monitor(master, csv_path, spectrum_path=None, update_interval_ms=10000):
    """
    Open the UV data plotting window.
    
    Args:
        master: Parent Tk window (or None to create root)
        csv_path: Path to the UV time-course CSV file
        spectrum_path: Optional path to spectrum CSV file (if None, will auto-detect)
        update_interval_ms: Auto-update interval in milliseconds (default: 10 seconds)
    
    Returns:
        UVDataPlotWindow instance
    """
    return UVDataPlotWindow(master, csv_path, spectrum_path, update_interval_ms)


def main():
    """Command-line entry point."""
    parser = argparse.ArgumentParser(
        description="Plot UV-Vis time-course data from CSV files"
    )
    parser.add_argument(
        "--csv-file",
        type=str,
        help="Path to the UV time-course CSV file"
    )
    parser.add_argument(
        "--spectrum-file",
        type=str,
        help="Path to the full spectrum CSV file (optional, will auto-detect if not provided)"
    )
    parser.add_argument(
        "--interval-ms",
        type=int,
        default=10000,
        help="Auto-update interval in milliseconds (default: 10000 = 10 seconds)"
    )
    
    args = parser.parse_args()
    
    # Use demo data if no file specified
    if args.csv_file is None:
        print("No CSV file specified. Creating demo data...")
        import numpy as np
        demo_path = Path("demo_uv_data.csv")
        
        # Generate sample data
        time = np.linspace(0, 300, 16)  # 5 minutes, 16 points
        wl1 = 0.1 + 0.5 * (1 - np.exp(-time / 60))  # Exponential rise
        wl2 = 0.8 - 0.3 * (1 - np.exp(-time / 80))  # Exponential decay
        
        demo_df = pd.DataFrame({
            "Time(s)": time,
            "409.0": wl1,
            "450.0": wl2
        })
        demo_df.to_csv(demo_path, index=False)
        print(f"Created demo data: {demo_path}")
        csv_file = demo_path
    else:
        csv_file = Path(args.csv_file)
        if not csv_file.exists():
            print(f"Error: File not found: {csv_file}")
            return
    
    # Handle spectrum file argument
    spectrum_file = Path(args.spectrum_file) if args.spectrum_file else None
    if spectrum_file and not spectrum_file.exists():
        print(f"Warning: Spectrum file not found: {spectrum_file}")
        print("Will attempt auto-detection instead.")
        spectrum_file = None
    
    # Create root window
    root = tk.Tk()
    root.withdraw()  # Hide root window
    
    # Open monitor window
    monitor = open_uv_plot_monitor(root, csv_file, spectrum_file, args.interval_ms)
    
    # Start main loop
    root.mainloop()


if __name__ == "__main__":
    main()
